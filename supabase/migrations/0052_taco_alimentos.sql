-- ============================================================
--  0052 — TACO na base: a referencia oficial de alimento de verdade
--
--  POR QUE ESTA TABELA EXISTE
--  O app "No mercado" julgava rotulo so com o que o modelo lia da foto e
--  sugeria marcas vindas da Open Food Facts, que e COLABORATIVA -- dado
--  digitado por usuario, com erro e com buraco. A Ana pediu que a TACO
--  passasse a ser a base das respostas. A TACO nao tem marca nem codigo de
--  barras (ela e tabela de alimento in natura e preparacoes), entao ela nao
--  substitui a OFF na indicacao de marca; ela entra como a REFERENCIA do
--  que o alimento de verdade tem, para comparar com o produto de pacote.
--
--  PROCEDENCIA
--  TACO 4a edicao ampliada e revisada (NEPA/Unicamp, 2011), PDF oficial
--  hospedado pelo CFN. Macros vindos da base que a plataforma ja usava no
--  editor de plano alimentar; sodio (Tabela 1) e gordura saturada (Tabela 2)
--  extraidos do PDF por mercado/extrai_taco.py, que so grava depois de
--  confirmar que o numero do alimento na TACO e o mesmo id da base (579
--  descricoes conferidas, 0 divergentes).
--
--  NULL AQUI QUER DIZER "NAO ANALISADO" (o "NA" da TACO), NUNCA ZERO.
--  Confundir os dois foi exatamente o defeito encontrado no ranking da OFF,
--  onde dado faltando virava nota boa. "Tr" (traco) da TACO virou 0.
--
--  Sem RLS de dono: e tabela de referencia publica, leitura para todos.
-- ============================================================

